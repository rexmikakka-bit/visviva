// Terminology follows EVE's own German client where the client has a word for it, which is why
// "Skill", "Fitting", "Booster", "Hardpoint", "Slot", "Rig", "Tab" and "Drop" stay as they are: CCP
// leaves them English in German EVE, and a player who reads "Fertigkeit" here would not recognise it
// from the game. Where the client DOES translate, we follow it — Panzerung (armor), Schild (shield),
// Hülle (hull), Signaturradius, Energienetz (powergrid). Item names, damage types and unit symbols
// are never translated at all.
//
// "Capacitor" stays English despite the client's "Kondensator": German players say capacitor, the
// same way they say Rig and Slot. "Hülle" is the word for a ship's hull; "Rumpf" reads as a torso or
// an aircraft fuselage.
//
// A value may be a form MAP instead of a string where the phrase counts something. German takes the
// same two forms as English, so `one` and `other` are all that appear here.
